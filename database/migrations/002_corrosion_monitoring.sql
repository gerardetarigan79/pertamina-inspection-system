-- Persist corrosion coupon and inhibitor monitoring in the shared Neon database.
CREATE TABLE IF NOT EXISTS corrosion_monitoring (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id TEXT NOT NULL REFERENCES assets(asset_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  reading_date DATE NOT NULL,
  coupon_id TEXT NOT NULL,
  coupon_initial_g NUMERIC(12,4) NOT NULL CHECK (coupon_initial_g > 0),
  coupon_final_g NUMERIC(12,4) NOT NULL CHECK (coupon_final_g >= 0 AND coupon_final_g <= coupon_initial_g),
  exposure_days INTEGER NOT NULL CHECK (exposure_days BETWEEN 1 AND 365),
  inhibitor TEXT NOT NULL DEFAULT '',
  injected_l NUMERIC(12,2) NOT NULL CHECK (injected_l >= 0),
  injection_rate_lpd NUMERIC(12,2) NOT NULL CHECK (injection_rate_lpd >= 0),
  notes TEXT NOT NULL DEFAULT '',
  source_system TEXT NOT NULL DEFAULT 'Form',
  is_sample BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT corrosion_monitoring_asset_date_coupon_key UNIQUE (asset_id, reading_date, coupon_id)
);

CREATE INDEX IF NOT EXISTS idx_corrosion_monitoring_asset_date
  ON corrosion_monitoring (asset_id, reading_date DESC);
