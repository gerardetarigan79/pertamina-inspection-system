-- Baseline source tables required by the existing API and unified asset register.
-- Column names/types follow fields selected and inserted by current API handlers.
-- Existing tables are left untouched. Asset foreign keys are added in migration 001.

CREATE TABLE IF NOT EXISTS production_readings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id TEXT NOT NULL,
  reading_date DATE NOT NULL,
  pressure_bar NUMERIC(14, 4),
  temperature_c NUMERIC(14, 4),
  gas_mmscfd NUMERIC(16, 6),
  water_bwpd NUMERIC(16, 4),
  oil_bopd NUMERIC(16, 4),
  source_system TEXT NOT NULL DEFAULT 'Direct Viewer',
  is_sample BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT production_readings_asset_date_key UNIQUE (asset_id, reading_date)
);

CREATE TABLE IF NOT EXISTS inspection_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id TEXT NOT NULL,
  inspection_date DATE NOT NULL,
  tml_id TEXT NOT NULL,
  method TEXT NOT NULL,
  nominal_wt_mm NUMERIC(14, 4) NOT NULL,
  measured_wt_mm NUMERIC(14, 4) NOT NULL,
  corrosion_type TEXT NOT NULL DEFAULT '',
  corrosion_depth_mm NUMERIC(14, 4),
  corrosion_length_mm NUMERIC(14, 4),
  corrosion_width_mm NUMERIC(14, 4),
  notification_no TEXT NOT NULL DEFAULT '',
  inspector_team TEXT NOT NULL DEFAULT '',
  source_system TEXT NOT NULL DEFAULT 'SAP',
  is_sample BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT inspection_records_asset_date_tml_key UNIQUE (asset_id, inspection_date, tml_id)
);

CREATE TABLE IF NOT EXISTS pipeline_inspections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  asset_id TEXT NOT NULL,
  inspection_date DATE NOT NULL,
  method TEXT NOT NULL,
  measured_thickness_mm NUMERIC(14, 4) NOT NULL,
  operating_pressure_bar NUMERIC(14, 4),
  inspector TEXT NOT NULL,
  remarks TEXT NOT NULL DEFAULT '',
  source_system TEXT NOT NULL DEFAULT 'Pipeline CSV',
  is_sample BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT pipeline_inspections_asset_date_method_thickness_key
    UNIQUE (asset_id, inspection_date, method, measured_thickness_mm)
);
